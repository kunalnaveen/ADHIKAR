/**
 * Global Helper Function to Translate any UI string into the target language.
 */
export function t(text: string, lang: Language): string {
  if (!text) return '';
  if (!lang || lang === 'EN') return text;

  // Exact match from dictionary
  const matchedObj = dictionary[text];
  if (matchedObj && matchedObj[lang]) {
    return matchedObj[lang];
  }

  // Trimmed lookup
  const trimmed = text.trim();
  const trimmedMatch = dictionary[trimmed];
  if (trimmedMatch && trimmedMatch[lang]) {
    return trimmedMatch[lang];
  }

  // Case insensitive match
  const lowerKey = Object.keys(dictionary).find(
    (k) => k.toLowerCase() === trimmed.toLowerCase()
  );
  if (lowerKey && dictionary[lowerKey][lang]) {
    return dictionary[lowerKey][lang];
  }

  // Return text as fallback
  return text;
}
