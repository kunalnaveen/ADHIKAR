/**
 * Translates numbers or digit strings to native regional digits when appropriate.
 */
export function translateNumber(num: number | string, lang: Language): string {
  if (lang === 'EN' || !lang) return String(num);
  const digits = nativeDigitMaps[lang] || nativeDigitMaps.EN;
  return String(num).replace(/[0-9]/g, (digit) => digits[parseInt(digit, 10)] || digit);
}

